import Foundation

enum AppLanguage: String, CaseIterable, Identifiable, Codable {
    case en, ru
    var id: String { rawValue }
    var title: String {
        switch self {
        case .en: return "English"
        case .ru: return "Русский"
        }
    }
}

enum Loc {
    /// Current UI language. English is the default; strings in code are English keys.
    static var lang: AppLanguage = AppLanguage(rawValue: UserDefaults.standard.string(forKey: "language") ?? "") ?? .en
}

/// Localizes an English template. Placeholders {0}, {1}, ... are replaced by `args`.
func L(_ key: String, _ args: Any...) -> String {
    var s = key
    if Loc.lang == .ru, let t = Translations.ru[key] { s = t }
    for (i, a) in args.enumerated() {
        s = s.replacingOccurrences(of: "{\(i)}", with: "\(a)")
    }
    return s
}

